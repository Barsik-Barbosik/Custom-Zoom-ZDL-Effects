# --- Fills --------------------------------------------------------------

def F(name: str, short: str, w: int, replace: str = "", crash: bool = False,
      **lanes: str) -> tuple[str, str, int, str, dict[str, str], bool]:
    if not 0 <= w <= 15:
        raise ValueError(f"fill {name}: window start {w} not in 0..15")
    unknown = (set(lanes) | set(replace)) - set(LANES)
    if unknown:
        raise ValueError(f"fill {name}: unknown lanes {unknown}")
    n = STEPS - w
    L: dict[str, str] = {}
    for l in LANES:
        s = lanes.get(l, "." * n)
        if len(s) != n or set(s) - {"x", "."}:
            raise ValueError(f"fill {name}: lane {l} must be {n} of 'x'/'.': {s!r}")
        L[l] = "." * w + s
    rep = set(replace)
    if rep & {"H", "O"} or "x" in L["H"] or "x" in L["O"]:
        rep |= {"H", "O"}
    if rep & {"T", "L"} or "x" in L["T"] or "x" in L["L"]:
        rep |= {"T", "L"}
    return (name, short, w, "".join(l for l in LANES if l in rep), L, crash)


def _rep(unit: str, n: int) -> str:
    return (unit * n)[:n]


LENGTHS = (("h", 2), ("1", 4), ("2", 8), ("4", 16))


def _family(prefix: str, title: str, lens: str, replace: str, make,
            crash: str = "") -> list:
    """One fill per length code in lens; make(n) -> lanes for an n-step window.
    Lengths listed in crash end with a crash on the next downbeat."""
    out = []
    for code, n in LENGTHS:
        if code in lens:
            out.append(F(f"{title} {code}", f"{prefix}{code}", STEPS - n, replace,
                         code in crash, **make(n)))
    return out


def _toms(s: str, split: int | None = None) -> dict[str, str]:
    """Tom hits s down the kit: steps before `split` (default: half the
    window) on the high tom T, the rest on the low tom L."""
    k = len(s) // 2 if split is None else split
    return {"T": s[:k] + "." * (len(s) - k), "L": "." * k + s[k:]}


def _snare_to_tom(n: int) -> dict[str, str]:
    # snare, then high tom, then low tom
    h = n // 2
    return {"S": "x" * h + "." * (n - h), **_toms("." * h + "x" * (n - h), h + (n - h) // 2)}


def _tom_to_snare(n: int) -> dict[str, str]:
    # high tom, low tom, then snare
    h = n // 2
    return {**_toms("x" * h + "." * (n - h), h // 2), "S": "." * h + "x" * (n - h)}


def _crescendo(n: int) -> dict[str, str]:
    # 8ths, then 16ths over the last beat; accents build up
    return {"S": _rep("x.", n - 4) + "xxxx", "A": _rep("x...", n - 4) + "x.x."}


def _tom_crescendo(n: int) -> dict[str, str]:
    # tom 8ths, then 16ths over the last beat (high, then low); accents build up
    return {**_toms(_rep("x.", n - 4) + "xxxx"), "A": _rep("x...", n - 4) + "x.x."}


def _cascade(n: int) -> dict[str, str]:
    # down the kit: snare 16ths, then high and low tom, then kick
    a, b = {8: (4, 2), 16: (6, 6)}[n]
    return {"S": "x" * a + "." * (n - a),
            **_toms("." * a + "x" * b + "." * (n - a - b), a + b // 2),
            "K": "." * (a + b) + "x" * (n - a - b)}


def _build(n: int) -> dict[str, str]:
    # snare density doubles every beat: quarters, 8ths, 16ths over the last beat
    s = {8: "x.x.xxxx", 16: "x...x...x.x.xxxx"}[n]
    return {"S": s, "K": _rep("x...", n), "A": "." * (n - 4) + "xxxx"}


def _around(n: int) -> dict[str, str]:
    # around the kit: snare, high tom, then low tom for the second half
    q = n // 4
    return {"S": "x" * q + "." * (n - q), "T": "." * q + "x" * q + "." * (n - 2 * q),
            "L": "." * (2 * q) + "x" * (n - 2 * q)}


def _bonham(n: int) -> dict[str, str]:
    # Bonham triplets: snare, tom, kick in groups of three 16ths; toms go
    # high, then low
    return {"S": _rep("x..", n), **_toms(_rep(".x.", n)), "K": _rep("..x", n)}


def _snare_into_toms(n: int) -> dict[str, str]:
    # snare 16ths, then the last beat down the toms (2 high, 2 low)
    return {"S": "x" * (n - 4) + "....", "T": "." * (n - 4) + "xx..",
            "L": "." * (n - 4) + "..xx"}


