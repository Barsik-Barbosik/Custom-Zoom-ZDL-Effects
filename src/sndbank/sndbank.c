/* rarely run engine code: one copy in .text, called (as SongBox's SS_COLD) */
#define SB_DO_PRAGMA(x) _Pragma(#x)
#define SB_EXPAND_PRAGMA(x) SB_DO_PRAGMA(x)
#define SS_COLD(f) SB_EXPAND_PRAGMA(FUNC_CANNOT_INLINE(f)) SB_EXPAND_PRAGMA(CODE_SECTION(f, ".text")) SB_EXPAND_PRAGMA(FUNC_INTERRUPT_THRESHOLD(f, 1))

#pragma CODE_SECTION(Fx_SFX_SndBank, ".audio")

#define SB_MAGIC  0x53424E35u           /* "SBN5"; new value on any state layout change */
#define SB_ID     ((7u << 24) | 531u)  /* own record word (SFX, FXID in build.py) */
#define SB_WT_STEP 1u                   /* wavetable rows per call (SongBox: SS_WT_STEP 3, ~4,000 cycles, in its
                                         * count-in); 1 keeps the peak low when SndBank moves to another slot
                                         * while all play (a delete before it: fresh arena, rebuild) */
#define SB_LOOK   64u                   /* calls between looks (~12 ms) */
#define SB_LWAIT  16u                   /* looks before the shadow is taken (~190 ms) */
#define SB_NK     9u                    /* knobs (columns 2..10) */
#define SB_NV     2u                    /* voices = MIDI channels 1, 2 (settings in knobs 1, 2) */
#define SB_NSOUND 9u                    /* sounds: SongBox's parts without the duplicates */
#define SS_INC0   0.000185392266f       /* note 0's phase step per sample (songbox_sound.h) */
#define SS_SEMI   1.05946309f           /* one semitone up (songbox_sound.h) */

/* One voice (SongBox's SsVoice, songbox.c). gate: open while > 0 (SongBox
 * counts it down in 16ths; here no countdown). */
typedef struct {
    float inc, p, p2, p3, env, menv, lp, lp2, bp, att, gate;
    uint32_t trig;
    uint32_t ip, ip2, ip3;              /* integer phases (2^32 = a cycle) */
} SsVoice;
#define SS_VCOPY(d, s) ((d).inc = (s).inc, (d).p = (s).p, (d).p2 = (s).p2, (d).p3 = (s).p3, \
    (d).env = (s).env, (d).menv = (s).menv, (d).lp = (s).lp, (d).lp2 = (s).lp2, (d).bp = (s).bp, \
    (d).att = (s).att, (d).gate = (s).gate, (d).trig = (s).trig, (d).ip = (s).ip, (d).ip2 = (s).ip2, (d).ip3 = (s).ip3)

#include "songbox_instr.h"              /* records, wavetable terms, parts (SongBox's) */

/* The engine's tables (the members engine.c reads) and the parts. */
typedef struct {
    uint32_t inst_pool[SS_NPOOL];
    uint32_t wt_terms[SS_WT_NTERMS];
    uint8_t wt_end[SS_WT_NEND];
    uint8_t part_id[SS_NKEYI + SS_NBASSI];      /* record | table << 4 */
    uint8_t part_lvl[SS_NKEYI + SS_NBASSI];     /* level * SS_LVL_DIV */
    uint8_t inst_idx[SS_NINSTB];
    uint32_t inst_mask[SS_NREC];
    uint8_t snd_part[SB_NSOUND];                /* sound number -> part */
} SsConst;
static const SsConst sb_c = {
    SS_INST_POOL_INIT, SS_WT_TERMS_INIT, SS_WT_END_INIT, SS_PART_ID_INIT, SS_PART_LVL_INIT,
    SS_INST_IDX_INIT, SS_INST_MASK_INIT,
    { 7, 11, 0, 1, 2, 3, 4, 5, 6 }      /* bass parts PB, Tr, then chords parts */
};

/* The info block's record (fxinfo.h): the sounds (names in sound order,
 * as snd_part), the played channels, the storage knobs (DATA: 1-9 at the
 * G1on field widths; the voice settings = the first 16 bits, knob 1's 13
 * and knob 2's low 3 (notebus.h NB_SV_*), are kept). */
#define SB_NREC (13u + SB_NSOUND)
static const uint32_t sb_info[SB_NREC] = {
    FI_ITEM(FI_SOUNDS, SB_NSOUND, 4u),
    FI_ENTRY4(FI_K_MELODIC, 'P', 'B', 0), FI_ENTRY4(FI_K_MELODIC, 'T', 'r', 0),
    FI_ENTRY4(FI_K_MELODIC, 'O', 'J', 0), FI_ENTRY4(FI_K_MELODIC, 'O', 'R', 0),
    FI_ENTRY4(FI_K_MELODIC, 'E', 'P', 0), FI_ENTRY4(FI_K_MELODIC, 'M', 'r', 0),
    FI_ENTRY4(FI_K_MELODIC, 'K', 'l', 0), FI_ENTRY4(FI_K_MELODIC, 'S', 'y', 0),
    FI_ENTRY4(FI_K_MELODIC, 'P', 'k', 0),
    FI_ITEM(FI_CHANNELS, 1u, 4u), (1u << SB_NV) - 1u,
    FI_ITEM(FI_DATA, 9u, 4u),
    FI_DATA4(1u, 13u, 13u), FI_DATA4(2u, 13u, 3u), FI_DATA4(3u, 13u, 0u),
    FI_DATA4(4u, 8u, 0u), FI_DATA4(5u, 8u, 0u), FI_DATA4(6u, 8u, 0u),
    FI_DATA4(7u, 8u, 0u), FI_DATA4(8u, 27u, 0u), FI_DATA4(9u, 8u, 0u),
};

#include "instruments/inst_lib.h"
#include "instruments/engine.c"         /* ss_wt_build, ss_run */

/* State at the ctx[3] arena's end below the info block (fxinfo.h: the
 * last FI_TOP + FI_AREA bytes; 64-B aligned, the MIDI in state first),
 * magic at both ends; the wavetables right below it (SB_WT_OF). */
typedef struct {
    MbIn in;                            /* MIDI in (midibus.h), 256 B */
    uint32_t magic0;
    uint32_t wait;                      /* calls until the next look */
    uint32_t fw;                        /* zm_fw_ok() at the last look */
    uint32_t note[SB_NV];               /* per voice: the held note (0x80 | note), 0 = none */
    uint32_t from[SB_NV];               /* per voice: slot of the sender of the held note */
    uint32_t snd[SB_NV];              /* per voice: sound number of the last note on */
    uint32_t nsnd[SB_NV], lvl[SB_NV];   /* per voice: the settings' sound (next note on), level */
    uint32_t wtn;                       /* wavetable rows built (SS_WT_ROWS: ready) */
    SsVoice v[SB_NV];                   /* the voices */
    SsInst inst[SS_NREC];               /* records (unpacked by ss_wt_build) */
    SsBlk blk[SS_NREC];                 /* their block steps */
    float acc[8], sf[8];                /* this call's samples, ss_run's scratch */
    uint32_t lslot, lwait, lok;         /* shadow: for slot, looks waited, valid */
    uint32_t sh[SB_NK];                 /* shadow: record values (knobs 1, 2: low bits) */
    uint32_t pend[SB_NK];               /* record values at the last look */
    uint32_t magic1;
} SbState;
#define SB_WT_BYTES (SS_WT_WORDS * 4u)
#define SB_WT_OF(st) ((uint32_t *)(((uintptr_t)(st) - SB_WT_BYTES) & ~(uintptr_t)7u))

/* The state, for the edit handler (the 4-byte .fardata). */
static volatile uint32_t sb_g = 0u;

void Fx_SFX_SndBank(unsigned int *ctx)
{
    unsigned int *magicSrc = (unsigned int *)(uintptr_t)ctx[12];
    unsigned int *magicDst = (unsigned int *)(uintptr_t)(*(unsigned int *)(uintptr_t)ctx[11]);
    float *params = (float *)(uintptr_t)ctx[1];
    float *fx = (float *)(uintptr_t)ctx[5];
    volatile unsigned int *arena = (volatile unsigned int *)(uintptr_t)ctx[3];
    SbState *st;
    uint32_t own = (uint32_t)ctx[0], fw, i, w, note, snd, r, id, b;
    float inc, s;

    *magicDst = *magicSrc;

    if (!arena) return;
    {
        uintptr_t base = (uintptr_t)arena[0];
        uintptr_t end = (uintptr_t)arena[1] & ~(uintptr_t)7u;
        if (base == 0u || end <= base + sizeof(SbState) + SB_WT_BYTES + FI_TOP + FI_AREA) return;
        st = (SbState *)((end - FI_TOP - FI_AREA - sizeof(SbState)) & ~(uintptr_t)63u);
    }
    if (st->magic0 != SB_MAGIC || st->magic1 != SB_MAGIC) {
        volatile uint8_t *b = (volatile uint8_t *)st;
#pragma UNROLL(1)
        for (i = 0u; i < sizeof(SbState); ++i) b[i] = 0u;
        st->lslot = own;
        st->in.chmask = (1u << SB_NV) - 1u;     /* channels 1, 2 */
        st->lvl[0] = st->lvl[1] = NB_SV_DEF;    /* until the first look */
        st->magic0 = SB_MAGIC;
        st->magic1 = SB_MAGIC;
    }
    sb_g = (uint32_t)(uintptr_t)st;

    /* the wavetables and records, a few rows per call until ready */
    if (st->wtn > SS_WT_ROWS) st->wtn = 0u;
    if (st->wtn < SS_WT_ROWS) {
        i = SS_WT_ROWS - st->wtn;
        if (i > SB_WT_STEP) i = SB_WT_STEP;
        ss_wt_build(&sb_c, SB_WT_OF(st), st->wtn, i, (uint32_t *)st->inst, st->blk);
        st->wtn += i;
    }

    if (st->wait) st->wait--;
    else {                              /* look: firmware, lock */
        st->wait = SB_LOOK;
        fw = zm_fw_ok();
        st->fw = fw;
        if (!fw || own >= zm_fws[fw - 1u].slots || ZM_U32(zm_fws[fw - 1u].rec + 44u * own + 4u) == SB_ID)
            fi_publish(ctx, sb_info, SB_NREC);  /* the sound list (not while the slot is being replaced) */
        if (!fw || own >= zm_fws[fw - 1u].slots || own != st->lslot
            || ZM_U32(zm_fws[fw - 1u].rec + 44u * own + 4u) != SB_ID) {
            st->lok = 0u;               /* no rows, moved, or being replaced: wait again */
            st->lwait = 0u;
            st->lslot = own;
        } else {
            volatile uint32_t *rr = (volatile uint32_t *)(uintptr_t)
                (zm_fws[fw - 1u].rec + 44u * own + 4u * NB_COL);
            w = NB_SV_CAT(rr[0], rr[1]);
#pragma UNROLL(1)
            for (b = 0u; b < SB_NV; ++b) {      /* the voice settings */
                snd = NB_SV_BYTE(w, b + 1u);
                r = (snd * 205u) >> 12;         /* snd / 20, exact below 1024 */
                if (r >= SB_NSOUND) {
                    r = 0u;
                    snd = NB_SV_DEF;
                }
                st->nsnd[b] = r;
                st->lvl[b] = snd - NB_LEVELS * r;
            }
            if (!st->lok) {
                if (++st->lwait >= SB_LWAIT) {
#pragma UNROLL(1)
                    for (i = 0u; i < SB_NK; ++i) {
                        r = i < SB_NV ? rr[i] & NB_LOWMASK : rr[i];
                        ((volatile SbState *)st)->sh[i] = r;
                        ((volatile SbState *)st)->pend[i] = r;
                    }
                    st->lok = 1u;
                }
            } else {
#pragma UNROLL(1)
                for (i = 0u; i < SB_NK; ++i) {
                    r = i < SB_NV ? rr[i] & NB_LOWMASK : rr[i];
                    if (r != st->sh[i] && r == st->pend[i])
                        ((volatile SbState *)st)->sh[i] = r;  /* the same twice: another effect's write */
                    ((volatile SbState *)st)->pend[i] = r;
                }
            }
        }
    }

    /* MIDI in, every call (channel c + 1 = voice c: chmask passes 1, 2) */
    {
        MbIn *mi = &st->in;             /* a plain local pointer: keeps midibus inlined */
        uint32_t ms, d1, d2;
        mb_in_poll(mi, ctx);
        w = mb_in_gone(mi);
#pragma UNROLL(1)
        for (b = 0u; b < SB_NV; ++b)    /* its sender gone: the held note ends */
            if (st->note[b] && (w >> st->from[b] & 1u)) {
                st->note[b] = 0u;
                st->v[b].gate = 0.0f;
            }
#pragma UNROLL(1)
        while (mb_in_next(mi, &ms, &d1, &d2)) {
            b = ms & 15u;
            r = ms & 0xF0u;
            if (r == 0x90u && d2) {     /* note on: SongBox's ss_trigger maths */
                st->note[b] = 0x80u | d1;
                st->from[b] = mi->from;
                st->snd[b] = st->nsnd[b];
                note = d1;
                inc = SS_INC0;
#pragma UNROLL(1)
                while (note >= 12u) { note -= 12u; inc *= 2.0f; }
#pragma UNROLL(1)
                for (; note; --note) inc *= SS_SEMI;
                st->v[b].inc = inc;
                st->v[b].gate = 1.0f;
                st->v[b].trig = 1u;
            } else if ((r == 0x80u || r == 0x90u) && st->note[b] == (0x80u | d1)) {
                st->note[b] = 0u;       /* note off of the held note */
                st->v[b].gate = 0.0f;
            }
        }
    }

    /* the voices (once the wavetables are ready) */
    if (st->wtn >= SS_WT_ROWS) {
        for (i = 0u; i < 8u; ++i) st->acc[i] = 0.0f;
#pragma UNROLL(1)
        for (b = 0u; b < SB_NV; ++b) {
            r = sb_c.snd_part[st->snd[b] < SB_NSOUND ? st->snd[b] : 0u];
            id = sb_c.part_id[r];       /* record | table << 4 */
            ss_run(&st->v[b], &st->inst[id & 15u], &st->blk[id & 15u],
                   (float)(sb_c.part_lvl[r] * st->lvl[b]) * (0.1f / SS_LVL_DIV), 0.0f, st->acc,
                   SB_WT_OF(st) + (id >> 4) * SS_WT_ROWS, st->sf);
        }
        if (params[0] >= 0.5f) {
            for (i = 0u; i < 8u; ++i) {
                s = st->acc[i];
                if (s > 1.98f) s = 1.98f;
                if (s < -1.98f) s = -1.98f;
                fx[i] += s;
                fx[8u + i] += s;
            }
        }
    }
}

typedef void (*SbWrite)(float *dst, float v, float k);

/* Edit handler of all 9 knobs (linker Param.edit; entered from the knob's
 * entry stub with A4 = state, B4 = column 2..10). The OS has just written
 * the turned value: put the shadow back into the table and record rows,
 * then the usual state[7] tail call (params unused). Only while the shadow's
 * slot still holds SndBank: an effect deleted before it moves it, and the
 * old slot then holds the next effect (its rows would get our values). */
#pragma FUNC_CANNOT_INLINE(Sb_LockEdit)
#pragma CODE_SECTION(Sb_LockEdit, ".text")
void Sb_LockEdit(uint32_t *state, uint32_t col)
{
    volatile SbState *st = (volatile SbState *)(uintptr_t)sb_g;
    union { uint32_t u; float f; } k;
    if (st && st->magic0 == SB_MAGIC && st->magic1 == SB_MAGIC && st->lok && st->fw &&
        col - NB_COL < SB_NK) {
        const ZmFw *t = &zm_fws[st->fw - 1u];
        uint32_t c = col - NB_COL, v = st->sh[c], o = 44u * st->lslot + 4u * col;
        if (st->lslot < t->slots && ZM_U32(t->rec + 44u * st->lslot + 4u) == SB_ID) {
            *(volatile uint32_t *)(uintptr_t)(t->tab + o) = v;
            *(volatile uint32_t *)(uintptr_t)(t->rec + o) = v;
            st->pend[c] = v;
        }
    }
    k.u = 0x44306666u;
    ((SbWrite)(uintptr_t)state[7])((float *)(uintptr_t)(state[1] + 12u + 4u * col), 0.0f, k.f);
}

/* Knob text of all 9 knobs (the values are stored data): "Data". Byte
 * stores, no table (no .rela.dyn entry). */
#pragma CODE_SECTION(GetString_SbData, ".text")
int GetString_SbData(unsigned int v, char *s)
{
    (void)v;
    s[0] = 'D'; s[1] = 'a'; s[2] = 't'; s[3] = 'a'; s[4] = 0;
    return 4;
}
