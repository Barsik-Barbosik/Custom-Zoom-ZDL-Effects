#!/usr/bin/env python3
"""Build SONGBOX.ZDL: chord song sequencer with synth bass and chords (SFX + 521).

  python -B build.py --out P        # SONGBOX.ZDL to P
  python -B build.py --probe --out P   # load probe: STATUS shows CPU % (SS_PROBE)
  python -B build.py --tests        # only regenerate songbox_tests.h (no TI)

Before compiling it regenerates songbox_sound.h (proto.py), songbox_instr.h
(sets.py + instruments/), songbox_drums.h
(DrumBox's patterns) and songbox_tests.h (packer test vectors from
packer/songpack.py; songbox.c doesn't include it). Saving songs needs
Floppy (src/floppy/build.py) on the pedal.
"""

from __future__ import annotations

import random
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
PROJECT = HERE.parent.parent                            # Custom-Zoom-ZDL/
ZMENU = HERE.parent / "common" / "zmenu"               # zmenu.h
SONG = HERE / "packer"
sys.path.insert(0, str(PROJECT / "build"))
sys.path.insert(0, str(SONG))
sys.path.insert(0, str(HERE / "patterns"))          # song_patterns.py, patterns.json

from screen_image import Canvas  # noqa: E402
from zdl_build import compile_c, encode_rle, link_common  # noqa: E402
import songpack as sp  # noqa: E402
import songseq as ref  # noqa: E402

GID = 7
SPACE = 3                                               # --opt_for_space (DrumBox: 3, works)
FXID = 521                                              # SFX + 521 (PigDrive is Drive + 521)

from song_patterns import DEFAULTS, DRUM_STYLES, PATTERNS  # noqa: E402  (patterns.json)
import proto  # noqa: E402  (patterns + note increments)
import sets  # noqa: E402  (instrument sets, instruments/)

KNOBS = [  # name, max, default
    ("Bar", 129, 1),  # 129: STATUS after 128 bars
    ("Chord", 26, 0), ("Rhythm", 2, 0),                  # Chord: END, 24 chords, Drums, Rest
    ("Rhy1", len(PATTERNS), DEFAULTS["Rhy1"]), ("Rhy2", len(PATTERNS), DEFAULTS["Rhy2"]),
    ("Rhy3", len(PATTERNS), DEFAULTS["Rhy3"]),           # 0 Randm, 1.. patterns (patterns.json)
    ("Tempo", 210, 60), ("Volume", 100, 50), ("Instr", len(sets.INSTR) - 1, 0),  # 40..250 BPM (max 210: APanDLY law, unclamped); 50 = x1; Instr = sets.INSTR
]


KNOB_SLOTS = [(1, 0), (126, 0), (127, 0)]                # blank 1x1 knobs, outside the frame


SCREEN = HERE / "screen.png"                              # 128x64, pixels darker than mid-grey = dark


def make_screen() -> bytes:
    from PIL import Image
    img = Image.open(SCREEN).convert("L")
    assert img.size == (128, 64), f"{SCREEN.name} is {img.size}, need 128x64"
    c = Canvas()
    for y in range(64):
        for x in range(128):
            c.px(x, y, 1 if img.getpixel((x, y)) <= 127 else 0)
    for x, y in KNOB_SLOTS:
        assert not any(c.pixels[y + z][x] for z in range(8)), f"knob slot {x},{y} not light"
    return encode_rle(c)


DRUMBOX = HERE.parent / "drumbox"
# Per pattern (DRUM_STYLES, from patterns.json): DrumBox beat, middle fill,
# end fill, bar2 fill (optional), by DrumBox screen name
# (../drumbox/patterns/). Middle and bar2 fills: no crash. The swing is the
# beat's.


def drumbox_patterns():
    sys.path.insert(0, str(DRUMBOX / "patterns"))
    import patterns as pt                               # DrumBox's
    return pt


def swing_codes() -> list:
    """Per pattern: its DrumBox beat's swing code (0 straight .. 3 tri8)."""
    pt = drumbox_patterns()
    return [pt.BEATS[pt.beat_index(DRUM_STYLES[p["short"]][0])][2].swing for p in PATTERNS]


def write_drums(out_h: Path) -> None:
    """ss_db_style[]: DrumBox knob values per style, and the swing amounts,
    from drumbox/patterns.py (regenerate after DrumBox's beat or fill lists
    change)."""
    pt = drumbox_patterns()
    rows = []
    for p in PATTERNS:
        beat, mid, end, bar2 = DRUM_STYLES[p["short"]]
        assert not pt.FILLS[pt.fill_index(mid)][5], f"middle fill {mid} crashes"
        assert not bar2 or not pt.FILLS[pt.fill_index(bar2)][5], f"bar2 fill {bar2} crashes"
        rows.append((p["short"], pt.beat_index(beat), pt.fill_index(mid), pt.fill_index(end),
                     pt.fill_index(bar2) if bar2 else 0, beat, mid, end, bar2 or "-"))
    # swing code -> amount, step bit: DrumBox's DB_SWING_AMT / DB_SWING_MASK (same float32)
    sw = sorted(pt.SWINGS.values())
    assert [c for c, _s, _b in sw] == [0, 1, 2, 3]
    mask = "1u"
    for code, _s, bit in sw:
        if bit != 1:
            mask = f"((c) == {code} ? {bit}u : {mask})"
    L = ["/* Generated by build.py from drumbox/patterns.py -- do not edit. */",
         "#ifndef SONGBOX_DRUMS_H", "#define SONGBOX_DRUMS_H",
         "/* per style: DrumBox BeatA, middle FillA, end FillA, bar2 FillA (knob values) */"]
    L += sets.c_init("SS_DB_STYLE_INIT", "ss_db_style[SS_NPAT * 4u]",
                [f"{b}u, {m}u, {e}u, {b2}u,    /* {name}: {bn}, {mn}, {en}, {b2n} */"
                 for name, b, m, e, b2, bn, mn, en, b2n in rows])
    L.append("#define SS_SWING_INIT { " + ", ".join(f"{s:.6f}f" for _c, s, _b in sw)
             + " }   /* ss_swing_amt[4], DrumBox's DB_SWING_AMT */")
    L.append(f"#define SS_SWING_MASK(c) {mask}   /* DrumBox's DB_SWING_MASK */")
    L += ["#endif", ""]
    out_h.write_bytes("\r\n".join(L).encode("ascii"))
    print(f"[songbox] DrumBox styles -> {out_h.name}: "
          + ", ".join(f"{r[0]} {r[5]}/{r[6]}/{r[7]}/{r[8]}" for r in rows))


def write_tests(out_h: Path) -> None:
    """Pack vectors (bars, Floppies -> bits, key, words hash; bits 0xFFFF =
    doesn't fit) and unpack vectors (any words, junk and markers too,
    Floppies -> bars, how the stream ended), all from songpack.py."""
    pk = sp.Packer()
    rng = random.Random(11)
    songs = [(s, 1) for s in sp.named_songs().values()]
    songs += [(ref.random_song(rng), 1) for _ in range(3)]
    full = None
    while full is None:                                 # one song that doesn't fit one Floppy, fits two
        bars = [(rng.randrange(12), rng.randrange(2), rng.randrange(3)) for _ in range(rng.randrange(20, 31))]
        if not pk.run([sp.to_byte(b) for b in bars]).fits and pk.run([sp.to_byte(b) for b in bars], 2).fits:
            full = bars
    songs.append((full, 1))
    songs.append((full, 2))
    for k in (3, 4):                                    # one song each, longer than k - 1 Floppies:
        bars = []                                       # in-key chords, any rhythm, until k - 1 overflow
        while pk.run([sp.to_byte(b) for b in bars], k - 1).fits:
            assert len(bars) < 120
            c = ref.chords("C Dm Em F G Am A#", rng.randrange(3))[rng.randrange(7)]
            bars += [c] * rng.randrange(1, 3)
        assert pk.run([sp.to_byte(b) for b in bars], k).fits
        songs.append((bars, k))

    blob: list[int] = []
    wblob: list[int] = []
    packs, unpacks = [], []
    for s, k in songs:
        bars = [sp.to_byte(b) for b in s]
        pk.run(bars, k)
        off = len(blob)
        blob += bars
        if pk.fits:
            packs.append((off, len(bars), k, pk.bits, pk.bkey, sp.words_hash(pk.words, k)))
        else:
            packs.append((off, len(bars), k, 0xFFFF, 0, 0))
        if k > 1:                                       # its stream read with one Floppy fewer:
            unpacks.append((list(pk.words[:4 * (k - 1)]), k - 1, off))  # a prefix of these bars

    values = [0, (13 | 1 << 4 | 5 << 7)]                # empty; junk key 13 + bars
    while len(values) < 10:
        v = rng.getrandbits(sp.KEY_BITS)
        for t in range(sp.NTOK):
            v |= (0 if rng.random() < 0.5 else rng.randrange(8)) << (sp.KEY_BITS + 3 * t)
        if len(sp.unpack(sp.to_words(v))) <= 40:
            values.append(v)
    unpacks = [(sp.to_words(v), 1, None) for v in values] + unpacks
    for k in (2, 3, 4):                                 # junk over k Floppies, with markers
        while True:
            w = [rng.getrandbits(32) for _ in range(4 * k)]
            for q in range(k):
                w[4 * q + 3] &= (1 << 10) - 1
                if q:
                    w[4 * q] = w[4 * q] & ~15 | (11 + q)
            if len(sp.unpack(w, k)) <= 40:
                break
        unpacks.append((w, k, None))
    ut = []
    for w, k, off in unpacks:
        bars, how = sp.unpack_end(w, k)
        with ref.parts(k):
            assert bars == [sp.to_byte(b) for b in ref.unpack(sp.to_value(w, k))]
        if off is None:
            off = len(blob)
            blob += bars
        assert blob[off:off + len(bars)] == bars
        ut.append((off, len(bars), k, len(wblob), how))
        wblob += w
    assert len(wblob) < 1 << 16 and len(blob) < 1 << 16

    L = ["/* Generated by build.py from songpack.py -- do not edit. */",
         "#ifndef SONGBOX_TESTS_H", "#define SONGBOX_TESTS_H",
         "typedef struct { uint16_t off; uint8_t n, parts; uint16_t bits; uint8_t key, pad; uint32_t h; } SsPackTest;",
         "typedef struct { uint16_t off; uint8_t n, parts; uint16_t woff; uint8_t how, pad; } SsUnpackTest;",
         f"#define SS_NPT {len(packs)}u",
         f"#define SS_NUT {len(ut)}u",
         "#define SS_NTEST (SS_NPT + SS_NUT)",
         f"static const uint8_t ss_t_bars[{max(1, len(blob))}] = {{"]
    for i in range(0, len(blob), 24):
        L.append("    " + ", ".join(f"{b}u" for b in blob[i:i + 24]) + ",")
    L.append("};")
    L.append(f"static const uint32_t ss_t_words[{len(wblob)}] = {{")
    for i in range(0, len(wblob), 6):
        L.append("    " + ", ".join(f"0x{x:08X}u" for x in wblob[i:i + 6]) + ",")
    L.append("};")
    L.append("static const SsPackTest ss_pt[SS_NPT] = {")
    for off, n, k, bits, key, h in packs:
        L.append(f"    {{ {off}u, {n}u, {k}u, {bits}u, {key}u, 0u, 0x{h:08X}u }},")
    L.append("};")
    L.append("static const SsUnpackTest ss_ut[SS_NUT] = {")
    for off, n, k, woff, how in ut:
        L.append(f"    {{ {off}u, {n}u, {k}u, {woff}u, {how}u, 0u }},")
    L += ["};", "#endif", ""]
    out_h.write_bytes("\r\n".join(L).encode("ascii"))
    print(f"[songbox] self-test: {len(packs)} pack + {len(ut)} unpack vectors, "
          f"{len(blob)} bar bytes, {len(wblob)} words -> {out_h.name}")


def main() -> None:
    for stream in (sys.stdout, sys.stderr):
        stream.reconfigure(encoding="utf-8", errors="replace")
    if "--tests" in sys.argv:                           # only songbox_tests.h (no TI)
        write_tests(HERE / "songbox_tests.h")
        return
    if "--out" not in sys.argv:
        sys.exit("[songbox] --out P required (SongBox builds never go to dist/)")
    out_zdl = Path(sys.argv[sys.argv.index("--out") + 1]).resolve()
    out_zdl.parent.mkdir(parents=True, exist_ok=True)
    from linker import LinkerConfig, link, params_from_manifest  # noqa: E402

    write_tests(HERE / "songbox_tests.h")
    proto.c_header(HERE / "songbox_sound.h", swing_codes())   # patterns, note increments
    sets.c_header(HERE / "songbox_instr.h")              # all instrument sets, Instr table
    write_drums(HERE / "songbox_drums.h")                # DrumBox control
    obj = HERE / "songbox.obj"
    defines = ["SS_PROBE=1"] if "--probe" in sys.argv else []   # never for dist/: --out is required
    compile_c(HERE / "songbox.c", obj, include=[ZMENU, SONG], defines=defines, space=SPACE)
    params = [dict(name=n, type="knob", max=mx, default=d, scale="enum", audio_min=0.0,
                   audio_max=float(mx), audio_default=float(d), getstr=f"GetString_Ss{i + 1}")
              for i, (n, mx, d) in enumerate(KNOBS)]
    link(LinkerConfig(
        effect_name="SongBox",
        audio_func_name="Fx_SFX_SongBox",
        gid=GID,
        fxid=FXID,
        params=params_from_manifest(params),
        obj_path=obj,
        output_path=out_zdl,
        fxid_version=b"1.00",
        flags_byte=1,
        screen_image=make_screen(),
        dsp_cost=45.0,                  # ~21 % mean per call (probe), chain budget 210 ~ the whole DSP
        # no firmware knobs on the picture: own blank 1x1 knob graphic (11 frames)
        knob_positions=[(i + 2, x, y) for i, (x, y) in enumerate(KNOB_SLOTS)],
        knob_bitmap=(1, 1, 11, bytes(11)),
        init_call_loop=True,            # one loop calls the cloned handlers (DrumBox b166)
        drop_ti_abs_symbols=True,       # as Floppy
        dynamic_entries=17,             # as Floppy
        rela_const_base=True,           # .const MVKL/MVKH relocations: one dynsym + addends
        drop_attributes=True,           # no .c6xabi.attributes section
        anon_edit_syms=True,            # knob handler dynsyms without names
        # 9 knob handlers = 16-byte stubs into one shared body (as Floppy);
        # Tempo's max 210 gives the body the 200 law for every knob
        **{**link_common(), "synth_edit_start_index": 0, "compact_edit_stubs": True},
    ))
    print(f"\n[songbox] done -> {out_zdl}")


if __name__ == "__main__":
    main()
