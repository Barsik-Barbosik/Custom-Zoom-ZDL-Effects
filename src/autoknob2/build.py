"""Build AutoKnob 2 (SFX + 524): two LFOs, each moving a knob of another effect.

  python -B build.py                      # release build -> ../../dist/AutoKnb2.ZDL
  python -B build.py --out P              # AutoKnb2.ZDL to P
  python -B build.py --probe --out P      # probe id SFX 1011, name AKProbe (test builds)

Writes autoknob_rates.h (generated: the Rate knob's phase steps). The screen
image is screen.png (128x64; pixels darker than mid-grey are dark). Knob
menu and bit map: see autoknob.c (top comment).
"""

from __future__ import annotations

import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
PROJECT = HERE.parent.parent                            # Custom-Zoom-ZDL/
sys.path.insert(0, str(PROJECT / "build"))            # linker, screen_image, zdl_build

from screen_image import Canvas  # noqa: E402
from zdl_build import compile_c, encode_rle, link_common  # noqa: E402

FXID = 524
PROBE_FXID = 1011                                       # 0x3F3, probe id
RATE_MIN_HZ = 0.05
RATE_MAX_HZ = 10.0
RATE_STEPS = 101                                        # Rate knob 0..100
CALLS_PER_SEC = 44100.0 / 8.0                           # audio calls per second
KNOB_SLOTS = [(1, 0), (126, 0), (127, 0)]                # blank 1x1 knobs, outside the frame
SCREEN = HERE / "screen.png"                              # 128x64, pixels darker than mid-grey = dark

# Knob menu (mirrors autoknob.c): rows of two values, packed widths
ROW_SHIFT = [0, 7, 7, 1]                                # A << shift | B (Dest: A * 9 + B)
ROW_WIDTH = [6, 10, 14, 6]
SEL_SHIFT = [11, 6]                                     # hidden bits below the row: knob 1 / 4
# defaults per LFO: Slot Knob Wave Rate Low High Phase Show (Slot 0 = Off)
DEFAULTS = [[0, 0, 0, 40, 0, 100, 0, 0],                # LFO 1: Off, Show Off
            [0, 0, 0, 40, 0, 100, 0, 0]]                # LFO 2: Off, Show Off
DEFAULT_ROWS = [0, 0]                                   # Dest


def rate_hz(k: int) -> float:
    """Rate knob k (0..100): exponential from RATE_MIN_HZ to RATE_MAX_HZ."""
    return RATE_MIN_HZ * (RATE_MAX_HZ / RATE_MIN_HZ) ** (k / (RATE_STEPS - 1))


def write_rates_header(path: Path) -> None:
    incs = [rate_hz(k) / CALLS_PER_SEC for k in range(RATE_STEPS)]
    lines = ["/* Generated by build.py: phase step per audio call for Rate 0..100",
             f" * ({RATE_MIN_HZ}..{RATE_MAX_HZ} Hz, exponential). Don't edit. */",
             "", f"#define AK_NRATES {RATE_STEPS}u", "",
             "static const float ak_inc[AK_NRATES] = {"]
    for i in range(0, RATE_STEPS, 6):
        lines.append("    " + " ".join(f"{x:.9e}f," for x in incs[i:i + 6]))
    lines += ["};", ""]
    path.write_bytes("\r\n".join(lines).encode("ascii"))


def pack_row(v: list[int], j: int) -> int:
    a, b = v[2 * j], v[2 * j + 1]
    return 9 * a + b if j == 0 else a << ROW_SHIFT[j] | b


def stream(v: list[int], row: int) -> int:
    """The hidden stream: rows other than the visible one, in order from bit 0."""
    s = n = 0
    for j in range(4):
        if j != row:
            s |= pack_row(v, j) << n
            n += ROW_WIDTH[j]
    return s


def default_columns() -> dict[int, int]:
    """Knob number (1..9) -> default value: the encoded DEFAULTS."""
    s0 = stream(DEFAULTS[0], DEFAULT_ROWS[0])
    s1 = stream(DEFAULTS[1], DEFAULT_ROWS[1])
    r0, r1 = DEFAULT_ROWS
    return {
        1: r0 << SEL_SHIFT[0] | (s0 & 0x7FF),
        2: DEFAULTS[0][2 * r0], 3: DEFAULTS[0][2 * r0 + 1],
        4: r1 << SEL_SHIFT[1] | (s1 & 0x3F),
        5: DEFAULTS[1][2 * r1], 6: DEFAULTS[1][2 * r1 + 1],
        7: s1 >> 6 & 0xFF,
        8: (s0 >> 11 & 0x7FFFF) | (s1 >> 22 & 0xFF) << 19,
        9: s1 >> 14 & 0xFF,
    }


def make_screen() -> bytes:
    """The screen image, loaded from SCREEN (edit the PNG to change it)."""
    from PIL import Image
    img = Image.open(SCREEN).convert("L")
    assert img.size == (128, 64), f"{SCREEN.name} is {img.size}, need 128x64"
    c = Canvas()
    for y in range(64):
        for x in range(128):
            c.px(x, y, 1 if img.getpixel((x, y)) <= 127 else 0)
    for x, y in KNOB_SLOTS:
        assert not any(c.pixels[y + z][x] for z in range(8)), f"knob slot {x},{y} not light"
    return encode_rle(c)


def build(out_zdl: Path, probe: bool) -> None:
    from linker import LinkerConfig, link, params_from_manifest  # noqa: E402

    write_rates_header(HERE / "autoknob_rates.h")
    dv = default_columns()
    print("  defaults: " + " ".join(f"k{k}={v}" for k, v in dv.items()))

    def sel(name: str, k: int, bits: int, getstr: str) -> dict:
        """Selector / storage knob: any value of its patch field, own edit handler."""
        return {"name": name, "type": "knob", "max": (1 << bits) - 1, "default": dv[k],
                "store": True, "scale": "enum", "audio_min": 0.0, "audio_max": 100.0,
                "audio_default": 0.0, "edit": "Ak_MenuEdit", "getstr": getstr}

    def val(name: str, k: int, getstr: str) -> dict:
        """Value knob: name and max rewritten per row at run time."""
        return {"name": name, "type": "knob", "max": 100, "default": dv[k], "scale": "enum",
                "audio_min": 0.0, "audio_max": 100.0, "audio_default": float(dv[k]),
                "getstr": getstr}

    params = [
        # page 1: LFO 1, page 2: LFO 2 (selector + the row's two values)
        sel("LFO1", 1, 13, "GetString_AkRow1"),
        val("Slot", 2, "GetString_AkVal2"),
        val("Knob", 3, "GetString_AkVal3"),
        sel("LFO2", 4, 8, "GetString_AkRow4"),
        val("Slot", 5, "GetString_AkVal5"),
        val("Knob", 6, "GetString_AkVal6"),
        # page 3: locked storage (8, 27, 8-bit patch fields); names and
        # texts "Data" (one shared getstr)
        sel("Data", 7, 8, "GetString_AkData"),
        sel("Data", 8, 27, "GetString_AkData"),
        sel("Data", 9, 8, "GetString_AkData"),
    ]
    obj = HERE / "autoknob.obj"
    compile_c(HERE / "autoknob.c", obj, defines=["AK_PROBE"] if probe else [])
    link(LinkerConfig(
        effect_name="AKProbe" if probe else "AutoKnb2",
        audio_func_name="Fx_SFX_AutoKnob",
        gid=7,
        fxid=PROBE_FXID if probe else FXID,
        params=params_from_manifest(params),
        obj_path=obj,
        output_path=out_zdl,
        fxid_version=b"1.00",
        flags_byte=1,
        screen_image=make_screen(),
        knob_positions=[(i + 2, x, y) for i, (x, y) in enumerate(KNOB_SLOTS)],
        knob_bitmap=(1, 1, 11, bytes(11)),
        # CPU probe (heavy patch, B1Xon): 2.5-4.0 % mean per call, peaks at
        # 1.0's level; 1.0 (~2.4 %) declared 6, SongBox (~15 %) 52
        dsp_cost=10.0,
        # size: SongBox's linker options
        init_call_loop=True,            # one loop calls the knob entry stubs
        drop_ti_abs_symbols=True,       # no TI bookkeeping symbols
        dynamic_entries=17,             # .dynamic without its DT_NULL padding
        rela_const_base=True,           # .const MVKL/MVKH relocations: one dynsym + addends
        anon_edit_syms=True,            # knob handler dynsyms without names
        rela_text_base=True,            # getstr targets: one dynsym + addends
        drop_empty_shdrs=True,          # no .rela.plt / .audio section headers
        anon_abi_syms=True,             # ABI dynsyms without names
        overlap_zero_tail=True,         # blank knob bitmap in imageInfo's zero tail
        **link_common(),
    ))


def main() -> None:
    args = sys.argv[1:]
    probe = "--probe" in args
    if probe:
        args.remove("--probe")
    if not args and not probe:                          # release build
        out = PROJECT / "dist" / "AutoKnb2.ZDL"
    elif len(args) == 2 and args[0] == "--out":
        out = Path(args[1]).resolve()
    else:
        sys.exit("usage: python -B build.py [--out P] | --probe --out P")
    out.parent.mkdir(parents=True, exist_ok=True)
    build(out, probe)


if __name__ == "__main__":
    for stream_ in (sys.stdout, sys.stderr):
        stream_.reconfigure(encoding="utf-8", errors="replace")
    main()
