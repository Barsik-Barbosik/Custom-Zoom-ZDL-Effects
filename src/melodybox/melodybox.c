/*
 * Melody Box (MeloBox): a note sequencer / player, in development.
 *
 * Knob 1 picks the mode: NOTE (value 0) or MENU (1 and 2).
 *
 * NOTE: knobs 1-3 show three neighbouring items of a list: "" (empty), the
 * steps 1..n (n = the LENGTH setting: 16, 32, 64 or 128), "END". A step's
 * name is its number (2 digits; after 99 again 00, 01, ..) plus its value:
 * "01___" rest, "01~~~" hold (the note before goes on), "01_C2" a natural
 * note, "01C#2" a sharp one (octaves 2..5: C2..C5). Knob 3 scrolls: its
 * value is the scroll offset, so turning it right moves the three knobs one
 * item on. Knob 2 edits the value of the step it shows (0 rest, 1 hold,
 * 2..38 = C2..C5); on a scroll it jumps to the new step's value. Knob
 * texts: knob 1 "NOTE", knob 2 its own name, knob 3 "SCROLL".
 *
 * MENU (as SongBox's): knob 2 picks the option (text LENGTH, STEP, SOUND),
 * the knob names spell its question, knob 3 gives the answer: LENGTH 16 /
 * 32 / 64 / 128 steps, STEP 1/16 or 1/8 (a step's length in playback),
 * SOUND the sound source's sound (PB .. Plk). Back on NOTE, knobs 2 and 3
 * jump back to the step and its value.
 *
 * The steps and settings live in the state only (ctx[3]): not saved with
 * the patch, lost on a patch switch.
 *
 * Playback (footswitch on): the n steps in a loop, a step = a 16th or an
 * 8th at the pedal tempo (the firmware's global BPM, 120 if unknown). A
 * note goes as a note on (pitch p = MIDI MB_BASE + p, the SOUND setting)
 * over the note bus (notebus.h) to the sound source SndBank (MB_SYN_ID) in
 * the chain, a note off at MB_GATE of its last step (holds after it make it
 * longer); a rest is silent. SndBank's slot is looked for at every step
 * start; footswitch off: a note off, stop.
 *
 * The names are the descriptor entries of knobs 1-3, rewritten by the audio
 * callback every call (the OS may restore them). When a name changed, the
 * screen is redrawn (3 Event_post calls, ZM_POST_GAP calls apart, only while
 * this effect is on screen and the firmware is known: zmenu.h's table).
 * The knob maxes (descriptor +0x0C) follow the mode. Jumps write the own
 * patch columns, so they need a known firmware (else a knob keeps its
 * position and a turn sets the value from there). Audio passes through
 * untouched.
 */

#include <stdint.h>

#define ZM_STREAM      1
#define ZM_DESC        _Fx_SFX_MeloBox_Desc
#define ZM_MAGIC       0x4D425831u      /* "MBX1" */
#define ZM_FLOPPY_FXID 522u             /* unused (no Floppy access) */
#define ZM_S_RANGE     1                /* own only the Floppies up to the next Floppy user */
#include "zmenu.h"
#include "notebus.h"
#ifdef MB_SELFTEST
#include "melopack.h"
#include "melodybox_selftest.h"         /* generated by build.py --selftest */
#endif

#pragma CODE_SECTION(Fx_SFX_MeloBox, ".audio")

#ifdef MB_SELFTEST
#define MB_MAGIC  0x4D425434u           /* "MBT4": the self-test build's layout */
#define MB_TUNITS 1u                    /* self-test: packer units per call */
#else
#define MB_MAGIC  0x4D425833u           /* "MBX3"; new value on any state layout change */
#endif
#define MB_NKNOB  3u                    /* knobs showing items */
#define MB_MODE   0u                    /* knob 1 (0-based): NOTE / MENU */
#define MB_EDIT   1u                    /* knob 2: the step's value / MENU option */
#define MB_SCROLL 2u                    /* knob 3: the scroll offset / MENU answer */
#define MB_MAXN   128u                  /* most steps */
#define MB_MAXOFF 127u                  /* knob 3 build max (run time: n - 1) */
#define MB_MAXVAL 38u                   /* knob 2 build max: 0 rest, 1 hold, 2..38 notes */
#define MB_REST   0u
#define MB_HOLD   1u
#define MB_NOPT   3u                    /* MENU options: */
#define MB_O_LEN  0u                    /* LENGTH: n = 16 << value */
#define MB_O_STEP 1u                    /* STEP: 0 = 1/16, 1 = 1/8 */
#define MB_O_SND  2u                    /* SOUND: the bus sound number */
#define MB_OMAX(o) ((o) == MB_O_LEN ? 3u : (o) == MB_O_STEP ? 1u : 11u)
#define MB_SYN_ID ((7u << 24) | 528u)   /* sound source: SndBank (SFX 528) */
#define MB_BASE   36u                   /* MIDI note of pitch 0 (C2: a bass octave) */
#define MB_GATE   0.75f                 /* note off at this part of the step */
#define MB_PH_PER_BPM 1.2093726e-05f    /* 16ths per audio call (8 samples) per BPM */
#define MB_G1_BPM 0x1181BB2Cu           /* G1on family: the global BPM int */
#define MB_NOSLOT 0xFFu

/* State at the ctx[3] arena's end, magic at both ends. */
typedef struct {
    uint32_t magic0;
    uint32_t posts, postWait;           /* redraws left, calls until the next */
    uint32_t mode;                      /* 0 NOTE, 1 MENU (2: jump to MENU's values) */
    uint32_t off, edit, k3;             /* scroll offset; knob 2 / knob 3 values as last seen */
    uint32_t opt, ov[MB_NOPT];          /* MENU option shown; values: length code, step, sound */
    uint8_t  grid[MB_MAXN];             /* step values: 0 rest, 1 hold, 2 + pitch */
    uint32_t play, step, len;           /* playing, step 0.., loop length in steps */
    float    ph;                        /* position in the step, 0..1 */
    uint32_t fw, slot;                  /* zm_fw_ok() and the sound source's slot, at the step start */
    uint32_t cnt, on;                   /* bus event counter last sent, a note is on */
#ifdef MB_SELFTEST
    uint32_t ti, tres, trep;            /* self-test: next decode vector, result, report timer */
    uint32_t pi, pgo;                   /* self-test: next pack vector, its job started */
    uint8_t  tgrid[MP_MAXN];            /* self-test: decoded grid */
    MpJob    job;                       /* self-test: the pack job */
#endif
    uint32_t magic1;
} MbState;

static volatile MbState *mb_g = 0;      /* for the knob text callbacks */

/* Note letters (index = pitch class + 1); sharps: 2, 4, 7, 9, 11. */
static const char mb_letter[13] = ".CCDDEFFGGAAB";
#define MB_SHARPS 0xA94u                /* bit i set: letter i is a sharp */

/* Texts: one pool of NUL-terminated strings (string i = mb_str(i)), <= 7
 * characters each. Knob texts, MENU answers, then the MENU questions (the
 * names of knobs 1, 2, 3 per option, one word per knob). */
#define MB_S_NOTE   0u
#define MB_S_MENU   1u
#define MB_S_SCROLL 2u
#define MB_S_OPT    3u                  /* LENGTH, STEP, SOUND */
#define MB_S_LEN    6u                  /* 16 .. 128 */
#define MB_S_STEP   10u                 /* 1/16, 1/8 */
#define MB_S_SND    12u                 /* PB .. Plk (SndBank's sound order) */
#define MB_S_Q      24u                 /* 3 words per option */
#define MB_VBASE(o) ((o) == MB_O_LEN ? MB_S_LEN : (o) == MB_O_STEP ? MB_S_STEP : MB_S_SND)
static const char mb_strs[] =
    "NOTE\0" "MENU\0" "SCROLL\0"
    "LENGTH\0" "STEP\0" "SOUND\0"
    "16\0" "32\0" "64\0" "128\0"
    "1/16\0" "1/8\0"
    "PB\0" "O1\0" "O2\0" "Sy\0" "Tr\0" "Or1\0" "Or2\0" "EP\0" "Mrm\0" "Klm\0" "Syn\0" "Plk\0"
    "Number\0" "of\0" "steps:\0"        /* LENGTH */
    "Each\0" "step\0" "is:\0"           /* STEP */
    "Play\0" "with\0" "sound:\0";       /* SOUND */

/* String i of the pool. */
#pragma FUNC_ALWAYS_INLINE(mb_str)
static inline const char *mb_str(uint32_t i)
{
    const char *p = mb_strs;
#pragma UNROLL(1)
    while (i) {
        if (*p++ == 0) i--;
    }
    return p;
}

/* Send one bus event (note 0 = off) to the sound source found at the step
 * start (none: nothing). */
#pragma FUNC_ALWAYS_INLINE(mb_send)
static inline void mb_send(volatile MbState *st, uint32_t note)
{
    volatile uint32_t *w;
    uint32_t cnt;
    if (!st->fw || st->slot == MB_NOSLOT) return;
    w = (volatile uint32_t *)(uintptr_t)(zm_fws[st->fw - 1u].tab + 44u * st->slot + 4u * NB_COL);
    cnt = st->cnt >= 15u ? 1u : st->cnt + 1u;
    st->cnt = cnt;
    *w = (*w & NB_LOWMASK) | NB_EVENT(cnt, note, st->ov[MB_O_SND]);
}

void Fx_SFX_MeloBox(unsigned int *ctx)
{
    unsigned int *magicSrc = (unsigned int *)(uintptr_t)ctx[12];
    unsigned int *magicDst = (unsigned int *)(uintptr_t)(*(unsigned int *)(uintptr_t)ctx[11]);
    float *params = (float *)(uintptr_t)ctx[1];
    volatile unsigned int *arena = (volatile unsigned int *)(uintptr_t)ctx[3];
    volatile MbState *st;
    uint32_t mode, r2, r3, k, n, x, tens, i, g, changed = 0u, fw, own, nmax;

    *magicDst = *magicSrc;              /* audio passes through untouched */

    if (!arena) return;
    {
        uintptr_t base = (uintptr_t)arena[0];
        uintptr_t end = (uintptr_t)arena[1] & ~(uintptr_t)3u;
        if (base == 0u || end <= base + sizeof(MbState)) return;
        st = (volatile MbState *)(end - sizeof(MbState));
    }
    mode = zm_knob(params[5 + MB_MODE], 2u) != 0u;
    r2 = zm_knob(params[5 + MB_EDIT], MB_MAXVAL);
    r3 = zm_knob(params[5 + MB_SCROLL], MB_MAXOFF);

    if (st->magic0 != MB_MAGIC || st->magic1 != MB_MAGIC) {
        st->magic0 = MB_MAGIC;
        st->posts = 0u;
        st->postWait = 0u;
#pragma UNROLL(1)
        for (i = 0u; i < MB_MAXN; i++) st->grid[i] = MB_REST;
        st->opt = MB_O_LEN;
        st->ov[MB_O_LEN] = 0u;          /* 16 steps */
        st->ov[MB_O_STEP] = 0u;         /* 1/16 */
        st->ov[MB_O_SND] = 0u;          /* PB */
        st->off = r3 > 15u ? 15u : r3;
        if (!mode) st->grid[st->off] = (uint8_t)r2;     /* knob 2's patch value: its step's */
        st->mode = mode ? 2u : 0u;      /* MENU: the knobs jump to its values below */
        st->edit = r2;
        st->k3 = r3;
        st->play = 0u;
        st->step = 0u;
        st->len = 16u;
        st->ph = 0.0f;
        st->fw = 0u;
        st->slot = MB_NOSLOT;
        st->cnt = 0u;
        st->on = 0u;
#ifdef MB_SELFTEST
        st->ti = 0u;
        st->tres = 0u;
        st->trep = 0u;
        st->pi = 0u;
        st->pgo = 0u;
#endif
        st->magic1 = MB_MAGIC;
    }
    mb_g = st;                          /* the active copy (knob texts) */
    n = 16u << st->ov[MB_O_LEN];
    fw = zm_fw_ok();
    own = fw && (uint32_t)ctx[0] < zm_fws[fw - 1u].slots;

    /* knob k jumps to v (own patch columns + params, as zmenu's jump);
     * unknown firmware: it stays (pickup) */
#define MB_JUMP(k, v, r) do { \
        if (own) { \
            zm_set_col(&zm_fws[fw - 1u], (uint32_t)ctx[0], 2u + (k), (v)); \
            params[5 + (k)] = (float)(v) * 0.01f; \
            (r) = (v); \
        } \
    } while (0)

    if (mode != st->mode) {
        /* NOTE <-> MENU: knobs 2 and 3 jump to the other mode's values */
        uint32_t v2, v3;
        st->mode = mode;
        if (mode) {
            v2 = st->opt;
            v3 = st->ov[st->opt];
        } else {
            v2 = st->grid[st->off];
            v3 = st->off;
        }
        MB_JUMP(MB_EDIT, v2, r2);
        MB_JUMP(MB_SCROLL, v3, r3);
        st->edit = r2;
        st->k3 = r3;
    } else if (mode) {
        if (r2 != st->edit) {
            /* MENU: another option; knob 3 jumps to its value */
            st->edit = r2;
            st->opt = r2 >= MB_NOPT ? MB_NOPT - 1u : r2;
            x = st->ov[st->opt];
            MB_JUMP(MB_SCROLL, x, r3);
            st->k3 = r3;
        } else if (r3 != st->k3) {
            /* MENU: the option's new value */
            st->k3 = r3;
            x = MB_OMAX(st->opt);
            st->ov[st->opt] = r3 > x ? x : r3;
            n = 16u << st->ov[MB_O_LEN];
            if (st->off >= n) st->off = n - 1u;
        }
    } else {
        x = r3 >= n ? n - 1u : r3;
        if (x != st->off) {
            /* scrolled: knob 2 jumps to its new step's value */
            st->off = x;
            g = st->grid[x];
            MB_JUMP(MB_EDIT, g, r2);
            st->edit = r2;
        } else if (r2 != st->edit) {
            /* knob 2 turned: the value of its step */
            st->edit = r2;
            st->grid[x] = (uint8_t)r2;
        }
        st->k3 = r3;
    }
#undef MB_JUMP

    /* knob maxes (descriptor +0x0C): knob 2 the values / options, knob 3 the
     * scroll range / the option's values; written only when changed */
    {
        volatile unsigned int *d = (volatile unsigned int *)ZM_DESC;
        uint32_t m2 = st->mode ? MB_NOPT - 1u : MB_MAXVAL;
        uint32_t m3 = st->mode ? MB_OMAX(st->opt) : n - 1u;
        if (d[12u * (2u + MB_EDIT) + 3u] != m2) d[12u * (2u + MB_EDIT) + 3u] = m2;
        if (d[12u * (2u + MB_SCROLL) + 3u] != m3) d[12u * (2u + MB_SCROLL) + 3u] = m3;
    }

    /* knob k's name. MENU: the option's question word k. NOTE: item off +
     * k: "" for item 0, "END" after step n, else the step's 2 digits, then
     * "___" (rest), "~~~" (hold), "_" + a natural note + octave or a sharp
     * note + octave */
    nmax = n;
#pragma UNROLL(1)
    for (k = 0u; k < MB_NKNOB; k++) {
        volatile unsigned char *nm = (volatile unsigned char *)&ZM_DESC[12u * (2u + k)];
        const char *q = 0;
        uint32_t item = st->off + k, c2, c3, c4, o, end = 0u;
        if (st->mode) q = mb_str(MB_S_Q + 3u * st->opt + k);
        x = item >= 100u ? item - 100u : item;
        tens = (x * 205u) >> 11;        /* x / 10, exact for x < 1029 */
        g = item - 1u < nmax ? st->grid[item - 1u] : MB_REST;
        if (g > MB_MAXVAL) g = MB_REST;
        if (g == MB_REST) c2 = c3 = c4 = '_';
        else if (g == MB_HOLD) c2 = c3 = c4 = '~';
        else {
            g -= 2u;                    /* pitch 0..36 */
            o = (g * 43u) >> 9;         /* g / 12, exact for g < 128 */
            g = g - 12u * o + 1u;       /* letter index 1..12 */
            c4 = '2' + o;
            if (MB_SHARPS >> g & 1u) { c2 = (uint32_t)mb_letter[g]; c3 = '#'; }
            else { c2 = '_'; c3 = (uint32_t)mb_letter[g]; }
        }
#pragma UNROLL(1)
        for (i = 0u; i < 8u; i++) {
            unsigned char v;
            if (q) {
                v = end ? 0u : (unsigned char)q[i];
                if (v == 0u) end = 1u;
            } else {
                v = item == 0u ? 0u :
                    item > nmax ? (i == 0u ? 'E' : i == 1u ? 'N' : i == 2u ? 'D' : 0u) :
                    i == 0u ? (unsigned char)('0' + tens) :
                    i == 1u ? (unsigned char)('0' + x - 10u * tens) :
                    i == 2u ? (unsigned char)c2 :
                    i == 3u ? (unsigned char)c3 :
                    i == 4u ? (unsigned char)c4 : 0u;
            }
            if (nm[i] != v) {
                nm[i] = v;
                changed = 1u;
            }
        }
    }
    if (changed) {
        st->posts = ZM_POSTS;
        st->postWait = 0u;
    }

#ifdef MB_SELFTEST
    /* self-test: decoder, one vector per call (n, step flag, FNV-1a hash of
     * the grid); then packer, one P vector at a time (key, bits, parts,
     * words); result into the own knob 1 record column for `patch`: 0
     * running, 1 all passed, 2000 + i decode vector i failed first, 3000 +
     * i pack vector i, 4000 + i its emitted bits != the DP's */
    if (st->ti < MB_NTEST) {
        uint32_t vv = mb_test.vec[st->ti][0], s8, nn, h, j;
        nn = mp_unpack(&mb_test.words[vv & 0xFFFFu], vv >> 16 & 15u, st->tgrid, &s8);
        h = 2166136261u;
#pragma UNROLL(1)
        for (j = 0u; j < nn; j++) h = (h ^ st->tgrid[j]) * 16777619u;
        if ((nn != 16u << (vv >> 24 & 3u) || s8 != (vv >> 20 & 15u) || h != mb_test.vec[st->ti][1])
            && !st->tres)
            st->tres = 2000u + st->ti;
        st->ti++;
    } else if (st->pi < MB_NPTEST) {
        uint32_t pv = mb_test.pvec[st->pi][0], pb = mb_test.pvec[st->pi][1], parts, j, bad;
        if (!st->pgo) {
            mp_start((MpJob *)&st->job, &mb_test.grids[pv & 0xFFFFu], 16u << (pv >> 16 & 3u), pv >> 18 & 3u);
            st->pgo = 1u;
        } else if (mp_run((MpJob *)&st->job, MB_TUNITS)) {
            parts = pv >> 20 & 15u;
            bad = st->job.okey != (pv >> 24 & 15u) || st->job.bits != (pb & 0xFFFFu)
                  || st->job.parts != parts;
#pragma UNROLL(1)
            for (j = 0u; j < 4u * parts && !bad; j++)
                bad = st->job.words[j] != mb_test.words[(pb >> 16) + j];
            if (!st->tres && st->job.err) st->tres = 4000u + st->pi;
            if (!st->tres && bad) st->tres = 3000u + st->pi;
            st->pgo = 0u;
            if (++st->pi == MB_NPTEST && !st->tres) st->tres = 1u;
        }
    } else if ((++st->trep & 4095u) == 0u) {
        if (own)
            *(volatile uint32_t *)(uintptr_t)(zm_fws[fw - 1u].rec + 44u * (uint32_t)ctx[0] + 4u * NB_COL)
                = st->tres;
    }
#endif

    /* playback: footswitch on plays the steps over the note bus */
    if (params[0] >= 0.5f) {
        uint32_t start = 0u, s;
        int b;
        if (!st->play) {                /* start at step 1 */
            st->play = 1u;
            st->step = 0u;
            st->ph = 0.0f;
            st->len = n;
            start = 1u;
        } else {
            x = st->fw;                 /* the pedal tempo (as SongBox's ss_pedal_bpm) */
            b = x ? (int)ZM_U32(zm_fws[x - 1u].mstride ? zm_fws[x - 1u].cursor + 8u : MB_G1_BPM) : 120;
            st->ph += (float)(b >= 40 && b <= 250 ? b : 120)
                      * (st->ov[MB_O_STEP] ? 0.5f * MB_PH_PER_BPM : MB_PH_PER_BPM);
            if (st->ph >= 1.0f) {       /* the next step */
                st->ph -= 1.0f;
                if (++st->step >= st->len) {
                    st->step = 0u;
                    st->len = n;
                }
                start = 1u;
            }
        }
        g = st->grid[st->step];
        if (start) {                    /* step start: the sound source, then the note */
            st->fw = x = zm_fw_ok();
            st->slot = MB_NOSLOT;
            if (x) {
#pragma UNROLL(1)
                for (s = 0u; s < zm_fws[x - 1u].slots; s++)
                    if (s != (uint32_t)ctx[0] && ZM_U32(zm_fws[x - 1u].rec + 44u * s + 4u) == MB_SYN_ID) {
                        st->slot = s;
                        break;
                    }
            }
            if (g >= 2u && g <= MB_MAXVAL) {
                mb_send(st, MB_BASE + g - 2u);
                st->on = 1u;
            } else if (st->on && (g != MB_HOLD || st->step == 0u)) {
                mb_send(st, 0u);        /* a rest (a hold at step 1 is one too) */
                st->on = 0u;
            }
        } else if (st->on && st->ph >= MB_GATE) {
            s = st->step + 1u;          /* the note's last step: off, else a hold follows */
            if (s >= st->len || st->grid[s] != MB_HOLD) {
                mb_send(st, 0u);
                st->on = 0u;
            }
        }
    } else if (st->play) {              /* footswitch off: stop */
        st->play = 0u;
        if (st->on) {
            mb_send(st, 0u);
            st->on = 0u;
        }
    }

    /* redraw after a rename (only on a known OS, own card on screen) */
    if (st->posts) {
        if (st->postWait) st->postWait--;
        else {
            st->posts--;
            st->postWait = ZM_POST_GAP;
            if (fw) {
                const ZmFw *t = &zm_fws[fw - 1u];
                if (zm_visible(t, (uint32_t)ctx[0]) && zm_in_ram(t->event) && !(t->event & 3u)) {
                    uint32_t ev = ZM_U32(t->event);
                    if (zm_in_ram(ev) && !(ev & 3u))
                        ((zm_post_fn)t->post)((void *)(uintptr_t)ev, 0x01u);
                }
            }
        }
    }
}

/* ---- knob texts (UI thread) ---- */

/* Knob k (0-based), value v: knob 1 NOTE / MENU; knob 2 its own name
 * (NOTE, descriptor entry 3 as the audio callback wrote it) or the MENU
 * option; knob 3 SCROLL or the MENU option's value. One shared copy in
 * .text. */
#pragma CODE_SECTION(mb_text, ".text")
#pragma FUNC_CANNOT_INLINE(mb_text)
static int mb_text(uint32_t k, uint32_t v, char *s)
{
    const volatile MbState *st = mb_g;
    const volatile unsigned char *nm = (const volatile unsigned char *)&ZM_DESC[12u * 3u];
    const char *p;
    uint32_t menu = st && st->mode == 1u, o;
    int n = 0;
    if (k == MB_MODE) p = mb_str(v ? MB_S_MENU : MB_S_NOTE);
    else if (k == MB_EDIT && menu) p = mb_str(MB_S_OPT + (v < MB_NOPT ? v : MB_NOPT - 1u));
    else if (k == MB_EDIT) {
#pragma UNROLL(1)
        while (n < 7 && nm[n] >= ' ' && nm[n] <= '~') {
            s[n] = (char)nm[n];
            n++;
        }
        s[n] = 0;
        return n;
    } else if (menu) {
        o = st->opt < MB_NOPT ? st->opt : MB_NOPT - 1u;
        p = mb_str(MB_VBASE(o) + (v < MB_OMAX(o) ? v : MB_OMAX(o)));
    } else p = mb_str(MB_S_SCROLL);
#pragma UNROLL(1)
    for (; n < 7 && p[n]; n++) s[n] = p[n];
    s[n] = 0;
    return n;
}

#pragma CODE_SECTION(GetString_Mb1, ".text")
int GetString_Mb1(unsigned int v, char *s) { return mb_text(0u, v, s); }
#pragma CODE_SECTION(GetString_Mb2, ".text")
int GetString_Mb2(unsigned int v, char *s) { return mb_text(1u, v, s); }
#pragma CODE_SECTION(GetString_Mb3, ".text")
int GetString_Mb3(unsigned int v, char *s) { return mb_text(2u, v, s); }
