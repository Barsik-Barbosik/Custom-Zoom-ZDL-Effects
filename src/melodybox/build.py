"""Build MeloBox.ZDL: Melody Box, a note sequencer / player (SFX 525).

  python -B src/melodybox/build.py --out P    # P = scratchpad until the first release
  python -B src/melodybox/build.py --selftest --out P   # + decoder self-test (see below)

Knob 1 = mode: NOTE (0) or MENU (1, 2). NOTE: knobs 1-3 show items
off .. off + 2 of "" (empty), steps 1..n, "END" (step name = 2 digits +
value: "01___" rest, "01~~~" hold, "01_C2", "01C#2"); knob 2 = the value of
its step (0 rest, 1 hold, 2..38 = C2..C5), knob 3 = scroll offset. MENU:
knob 2 = option LENGTH / STEP / SOUND, knob 3 = its value, the names spell
the question. Knob maxes change at run time. See melodybox.c.

--selftest: writes melodybox_selftest.h (generated, from
packer/melopack_vectors.txt) and builds with MB_SELFTEST: after a fresh
state the audio call decodes one vector per call with packer/melopack.h
(the P lines' words and the U lines) and compares n, the step flag and an
FNV-1a hash of the grid; then it packs each P line's grid (mp_start +
mp_run, a few units per call) and compares key, bits, parts and words.
The result goes into MeloBox's own knob 1 record column (read with
`g1on_sysex.py patch`): 0 running, 1 all passed, 2000 + i decode vector i
(0-based, file order) failed first, 3000 + i pack vector i (0-based, P
lines only) failed, 4000 + i its emitted bits differ from the DP's. Not
for a release; knob 1 is the NOTE / MENU knob now, so the result puts the
editor into MENU (use the self-test build only for the packer test).
"""

from __future__ import annotations

import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
PROJECT = HERE.parent.parent                            # Custom-Zoom-ZDL/
sys.path.insert(0, str(PROJECT / "build"))            # linker, screen_image, zdl_build

from zdl_build import compile_c, link_common  # noqa: E402

FXID = 525
MAX_OFF = 127                                           # mirrors MB_MAXOFF in melodybox.c
MAX_VAL = 38                                            # mirrors MB_MAXVAL in melodybox.c
ZMENU = PROJECT / "src" / "common" / "zmenu"
PACKER = HERE / "packer"
NOTEBUS = PROJECT / "src" / "common" / "notebus"


def fnv(data: bytes) -> int:
    """FNV-1a 32 (mirrors mb_fnv in melodybox.c)."""
    h = 2166136261
    for b in data:
        h = ((h ^ b) * 16777619) & 0xFFFFFFFF
    return h


def write_selftest(path: Path) -> int:
    """melodybox_selftest.h from packer/melopack_vectors.txt; returns the
    number of vectors. Each: words (4 per part) in one pool; vec = word
    offset | parts << 16 | step flag << 20 | log2(n / 16) << 24, then the
    grid's FNV-1a hash. Pack vectors (P lines) also: pvec = grid offset in
    the byte pool | log2(n / 16) << 16 | step flag << 18 | parts << 20 | key
    << 24, then token bits | word offset << 16 (their words: the same pool)."""
    pool: list = []
    vecs: list = []
    pvecs: list = []
    grids = bytearray()
    for line in (PACKER / "melopack_vectors.txt").read_text().splitlines():
        f = line.split()
        if not f or f[0] not in ("P", "U"):
            continue
        grid = bytes.fromhex(f[-1])
        code = {16: 0, 32: 1, 64: 2, 128: 3}[len(grid)]
        if f[0] == "P":                     # P bits key step parts words.. grid
            bits, key, step, parts = int(f[1]), int(f[2]), int(f[3]), int(f[4])
            words = f[5:5 + 4 * parts]
            pvecs.append((len(grids) | code << 16 | step << 18 | parts << 20 | key << 24,
                          bits | len(pool) << 16))
            grids += grid
        else:                               # U parts step words.. grid
            parts, step = int(f[1]), int(f[2])
            words = f[3:3 + 4 * parts]
        vecs.append((len(pool) | parts << 16 | step << 20 | code << 24, fnv(grid)))
        pool += [int(w, 16) for w in words]
    lines = ["/* Generated by build.py --selftest from packer/melopack_vectors.txt -- do not edit. */",
             f"#define MB_NTEST {len(vecs)}u",
             f"#define MB_NTWORDS {len(pool)}u",
             f"#define MB_NPTEST {len(pvecs)}u",
             f"#define MB_NGRID {len(grids)}u",
             "static const struct {",
             "    uint32_t vec[MB_NTEST][2];",
             "    uint32_t pvec[MB_NPTEST][2];",
             "    uint32_t words[MB_NTWORDS];",
             "    uint8_t grids[MB_NGRID];",
             "} mb_test = {",
             "  {"]
    lines += [f"    {{ 0x{a:08X}u, 0x{b:08X}u }}," for a, b in vecs]
    lines += ["  }, {"]
    lines += [f"    {{ 0x{a:08X}u, 0x{b:08X}u }}," for a, b in pvecs]
    lines += ["  }, {"]
    for i in range(0, len(pool), 6):
        lines.append("    " + " ".join(f"0x{w:08X}u," for w in pool[i:i + 6]))
    lines += ["  }, {"]
    for i in range(0, len(grids), 16):
        lines.append("    " + " ".join(f"{b}," for b in grids[i:i + 16]))
    lines += ["  }", "};", ""]
    path.write_bytes("\r\n".join(lines).encode("ascii"))
    return len(vecs)


def build(out_zdl: Path, selftest: bool = False) -> None:
    from linker import LinkerConfig, link, params_from_manifest  # noqa: E402

    def knob(name: str, mx: int, getstr: str) -> dict:
        return {"name": name, "type": "knob", "max": mx, "default": 0, "scale": "enum",
                "audio_min": 0.0, "audio_max": float(mx), "audio_default": 0.0,
                "getstr": getstr}

    params = [
        knob("", 2, "GetString_Mb1"),                  # mode: NOTE / MENU
        knob("01___", MAX_VAL, "GetString_Mb2"),       # step value / MENU option
        knob("02___", MAX_OFF, "GetString_Mb3"),       # scroll / MENU answer
    ]
    obj = HERE / "melodybox.obj"
    defines = []
    if selftest:
        print(f"  self-test: {write_selftest(HERE / 'melodybox_selftest.h')} vectors")
        defines = ["MB_SELFTEST"]
    compile_c(HERE / "melodybox.c", obj, include=[ZMENU, NOTEBUS, PACKER], defines=defines)
    link(LinkerConfig(
        effect_name="MeloBox",
        audio_func_name="Fx_SFX_MeloBox",
        gid=7,
        fxid=FXID,
        params=params_from_manifest(params),
        obj_path=obj,
        output_path=out_zdl,
        fxid_version=b"0.10",
        flags_byte=1,
        dsp_cost=1.0,
        **link_common(),
    ))
    obj.unlink(missing_ok=True)


def main() -> None:
    args = sys.argv[1:]
    selftest = "--selftest" in args
    if selftest:
        args.remove("--selftest")
    if len(args) == 2 and args[0] == "--out":
        out = Path(args[1]).resolve()
    else:
        sys.exit("usage: python -B src/melodybox/build.py [--selftest] --out P")
    out.parent.mkdir(parents=True, exist_ok=True)
    build(out, selftest)


if __name__ == "__main__":
    for stream_ in (sys.stdout, sys.stderr):
        stream_.reconfigure(encoding="utf-8", errors="replace")
    main()
