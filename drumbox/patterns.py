"""DrumBox beats and fills -- edit here, build.py regenerates drumbox_patterns.h.

The sequencer plays a song of two sections in turn:
  section A  BeatA for LenA bars, FillA laid over the end of its last bar
  section B  BeatB for LenB bars, FillB laid over the end of its last bar
A crash fill puts a crash on beat 1 of the next section (FillB's also
when the footswitch starts the song), unless the last crash is less than
4 bars back (DB_CRASH_GAP; short sections crash every 4th bar at most);
a middle fill (Len ..M) never crashes. Knobs: BeatA / BeatB pick from
BEATS (beat 0 = "None": no beat, the fills play over silence; beat 1 =
"Randm": a random beat, a new one at every start of its section), FillA /
FillB pick from FILLS (shared list; fill 0 = "None", plain beat). Beats
carry no crash of their own: the crash comes with the fills (a crash on every
phrase start gets annoying).

BEATS: one 4/4 bar of 16 sixteenth steps. 'x' = hit, '.' = rest. Lanes:
  K = kick, S = snare, H = closed hat, O = open hat, R = ride, C = crash,
  T = high tom, A = accent (hits on accented steps play louder; default:
  every beat), L = low tom.
A closed hat on the same step as an open hat is rejected (closed chokes open).
P(name, screen, swing=..., **lanes). Keep the C lane empty in grooves (Stop is the
exception: its one hit is the point).
swing (SWINGS, default straight): the
beat's feel, also under fills. "sw16" / "sw16h" delay every odd 16th
(light ~1.4:1 MPC-style / heavy ~1.7:1 pairs); "tri8" delays the second
8th of each beat to its last triplet (2:1 shuffle): steps 0, 1, 2 of a
beat land on its three triplet 8ths, step 3 halfway from step 2 to the
next beat (avoid it). Write shuffles as straight 8ths with "tri8", not
in dotted notation.

FILLS: a window at the end of the bar (from step w to 15) laid over beat A.
Lanes listed in `replace` are cleared inside the window (A's hits there are
dropped); the other lanes keep A's hits and the fill's hits are added.
F(name, screen, w, replace, **lanes): each lane string covers the window
only (16 - w steps). A fill that writes or clears H or O replaces both
(so A's closed hat never chokes the fill's open hat); one that writes or
clears T or L replaces both toms (A's toms don't clutter the fill's run). A fill's own C hits
always play. crash=True adds a crash on beat 1 of the bar after the fill
(the classic "fill, then crash"); light fills (pickups, open hats, half-beat
rolls, hats-only, hits, stops) have none. Most fills are generated by FAMILIES x lengths (h = half a beat,
1 = one beat, 2 = two beats, 4 = the whole bar); see _generated_fills().

Screen names (what the knobs show on the pedal): 1..5 printable ASCII, no
spaces, unique within BEATS and within FILLS. Knob value v selects entry
min(v, count - 1); order the lists so neighbours are related.
"""

